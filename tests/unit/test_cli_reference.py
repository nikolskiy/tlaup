"""The generated command-line reference does not drift, and every command has a description (design 23 C5)."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import TYPE_CHECKING, Any

import typer.main

import tlaup.cli
from tests.expected import assert_matches

if TYPE_CHECKING:
    from collections.abc import Iterator
    from types import ModuleType

    import pytest

    from tests.conftest import Isolated

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs" / "reference" / "cli.md"


def _script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("gen_cli_reference", ROOT / "scripts" / "gen_cli_reference.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _walk(command: Any, path: tuple[str, ...]) -> Iterator[tuple[tuple[str, ...], Any]]:
    yield path, command
    for name, sub in getattr(command, "commands", {}).items():
        yield from _walk(sub, (*path, name))


def test_reference_matches_the_app(isolated: Isolated, request: pytest.FixtureRequest) -> None:
    text = _script().render_reference(tlaup.cli.app)
    assert text.splitlines()[0].startswith("<!-- Generated by scripts/gen_cli_reference.py")
    assert str(isolated.home.parent) not in text
    assert_matches(text, REFERENCE, request)


def test_every_command_has_help() -> None:
    """Row P5: a one-line description beside every command, and each option of tlc described."""
    root = typer.main.get_command(tlaup.cli.app)
    missing = []
    for path, command in _walk(root, ()):
        short = command.short_help or (command.help or "").strip().splitlines()[:1]
        if not short:
            missing.append(" ".join(("tlaup", *path)))
    assert missing == []
    undescribed = [p.name for p in root.commands["tlc"].params if p.param_type_name == "option" and not p.help]
    assert undescribed == []
